def main():
    print(
        "# Ground truth for the external work item serializer, generated by "
        "apps/api-go/tools/generate_external_issue_validation_fixture.py. Do not edit by hand."
    )
    print("# Each row is a JSON payload, the outcome, and the JSON body DRF answers with. VALID means it was accepted.")
    for case in CASES:
        serializer = IssueSerializer(
            data=case,
            context={"project_id": None, "workspace_id": None, "default_assignee_id": None},
        )
        if serializer.is_valid():
            # A payload that is accepted is reported with what the serializer made of its description, which is the one field it rewrites.
            rendered = serializer.validated_data.get("description_html", "")
            print(f"{json.dumps(case, sort_keys=True)}\tVALID\t{json.dumps(rendered)}")
            continue
        errors = json.loads(json.dumps(serializer.errors, default=str))
        print(f"{json.dumps(case, sort_keys=True)}\tINVALID\t{json.dumps(errors, sort_keys=True)}")


if __name__ == "__main__":
    main()
