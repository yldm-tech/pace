#!/usr/bin/env python
"""Emit what the external API's IssueSerializer says about a bad work item payload.

`internal/externalapi` answers with the serializer's own errors, and a body that differs from DRF's is a body no integration can read. The fixture this writes is what its test diffs against.

Only payloads that are decided without reading a row are listed, so the fixture is the same whether or not a database is in reach. The checks that do look a row up — a state in another project, a parent that does not exist — are covered by tests of their own.

Run from apps/api against a configured Django:

    python ../api-go/tools/generate_external_issue_validation_fixture.py > ../api-go/internal/externalapi/testdata/issue_validation.tsv
"""

